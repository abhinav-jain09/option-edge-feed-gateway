/**
 * The calibrated release of CHART-STRUCTURE-TOOLS (StructureToolsSet version 2, id 2212) and CLASSICAL-CHART-PATTERNS (GeometryAnnotationSet version 2, id 2223): the tools and
 * geometry relays forward the measured evidence VERBATIM. The records here are the bytes the REAL producer serializer wrote (market-structure-service of options-edge-processing,
 * commits 1fe3b6372 and fd201987; oracle vectors / designed price paths through the real fold, the producer's own Avro mapping under the measured parameter set; generated by the web
 * repository's scripts/geometry-fixtures generators, last argument): they pass through the production {@link GatewayAvroDeserializer} against a registry that holds the version-2 schema
 * under the producer's test ids, then through {@link TimeframeSetRelay}; the frame must equal, node for node, the JSON the generator wrote from the decoded record by its OWN code
 * (independent of the gateway's renderer). The gateway adds, drops and renames nothing and judges none of the new vocabularies (the page is the full validator).
 */
class CalibratedMarketStructureProducerRecordsTest {
    private static final ObjectMapper JSON = new ObjectMapper();
    private static final String TOOLS_SUBJECT = "com.optionsedge.contracts.marketstructure.tools.StructureToolsSet";
    private static final String GEOMETRY_SUBJECT = "com.optionsedge.contracts.marketstructure.geometry.GeometryAnnotationSet";
    private static final List<String> SCOPES = List.of("bc-tools", "bc-geometry", "bc-size", "bc-v1");

    /** The mock registry keeps its scopes in static state: drop them so nothing leaks into another test of the JVM. */
    @AfterAll
    static void dropScopes() {
        SCOPES.forEach(io.confluent.kafka.schemaregistry.testutil.MockSchemaRegistry::dropScope);
    }

    private static JsonNode records(String file) throws Exception {
        try (InputStream in = CalibratedMarketStructureProducerRecordsTest.class.getResourceAsStream("/ta-producer/" + file)) {
            return JSON.readTree(in).get("records");
        }
    }

    private static Schema schema(String dir, String name) throws Exception {
        try (InputStream in = CalibratedMarketStructureProducerRecordsTest.class.getResourceAsStream("/" + dir + "/" + name + ".avsc")) {
            return new Schema.Parser().parse(new String(in.readAllBytes(), java.nio.charset.StandardCharsets.UTF_8));
        }
    }

    private static GatewayAvroDeserializer deserializer(String scope, String topic, String subject, String name, int id) throws Exception {
        SchemaRegistryClient registry = io.confluent.kafka.schemaregistry.testutil.MockSchemaRegistry.getClientForScope(scope);
        registry.register(subject, new AvroSchema(schema("ta", name)), 1, id);
        Map<String, Object> reader = new HashMap<>();
        reader.put("schema.registry.url", "mock://" + scope);
        reader.put("auto.register.schemas", false);
        reader.put("value.subject.name.strategy", "io.confluent.kafka.serializers.subject.RecordNameStrategy");
        reader.put("specific.avro.reader", "false");
        reader.put(GatewayAvroDeserializer.SPX_PRICE_TOPIC, "underlying.spx.price");
        reader.put(GatewayAvroDeserializer.TOLERANT_TOPICS, topic);
        GatewayAvroDeserializer d = new GatewayAvroDeserializer();
        d.configure(reader, false);
        return d;
    }

    private static JsonNode frameData(String[] frame) throws Exception {
        assertNotNull(frame);
        return JSON.readTree(frame[1]);
    }

    @Test
    void everyRealToolsRecordIsRelayedAsTheExactJsonTheProducerSideDecodingWrote() throws Exception {
        JsonNode records = records("structure-tools-records.json");
        assertEquals(4, records.size());
        try (GatewayAvroDeserializer d = deserializer("bc-tools", "t.bct", TOOLS_SUBJECT, "StructureToolsSet", 111)) {
            for (JsonNode r : records) {
                byte[] bytes = Base64.getDecoder().decode(r.get("framedBase64").asText());
                assertEquals(111, java.nio.ByteBuffer.wrap(bytes, 1, 4).getInt(), "the producer's own frame");
                Object decoded = d.deserialize("t.bct", bytes);
                assertTrue(decoded instanceof GenericRecord, r.get("name").asText() + " must decode, not be UNDECODABLE");
                var relay = TimeframeSetRelay.structureTools();
                String[] frame = relay.onLive(r.get("event").asText(), decoded);
                assertEquals(TimeframeSetRelay.TOOLS_EVENT, frame[0]);
                assertEquals(r.get("data"), frameData(frame), r.get("name").asText() + ": the frame is the record, verbatim");
                assertEquals(0, relay.dropsForTest());
                assertEquals(1, relay.acceptedForTest());
            }
        }
    }

    @Test
    void theMeasuredToolsEvidenceReachesTheHelloAndTheLiveFrameWithItsFixedStatementsUntouched() throws Exception {
        JsonNode records = records("structure-tools-records.json");
        try (GatewayAvroDeserializer d = deserializer("bc-size", "t.bcs", TOOLS_SUBJECT, "StructureToolsSet", 111)) {
            var relay = TimeframeSetRelay.structureTools();
            JsonNode calibrated = null;
            for (JsonNode r : records) {
                if (r.get("name").asText().startsWith("GAP") && !r.get("name").asText().contains("another")) {
                    String[] frame = relay.onLive(TimeframeSetRelay.TOOLS_EVENT, d.deserialize("t.bcs", Base64.getDecoder().decode(r.get("framedBase64").asText())));
                    calibrated = frameData(frame);
                }
            }
            assertNotNull(calibrated);
            JsonNode hello = JSON.readTree("{" + relay.helloField(Long.MAX_VALUE).substring(1) + "}").get("tools").get("5m");
            assertEquals(calibrated, hello, "the hello carries the retained set whole");
            int measured = 0;
            for (JsonNode o : hello.get("objects")) {
                assertEquals("VALIDATED", o.get("calibration").asText());
                assertEquals("CALIBRATED", o.get("calibrationState").asText());
                assertEquals("MEASURED", o.get("validationState").asText());
                JsonNode e = o.get("evidence");
                assertEquals(o.get("measuredEdge").asText().equals("EXACT_CONSTRUCT") ? "no direction claim" : e.get("claim").asText(), e.get("claim").asText());
                assertTrue(e.get("statement").asText().length() > 0 && e.get("scaleStatement").asText().startsWith("time scale: "));
                assertTrue(e.get("validationResultId").asText().startsWith("TC-CAL-1#"));
                assertEquals("f40c7965c935e19f1085d5849dd94bac0ea3f2867da08d96edbb337eb8284f3e", e.get("datasetSha256").asText());
                assertEquals(20210104, e.get("validationFromDay").asInt());
                assertEquals(20261009, e.get("validationToDay").asInt());
                assertFalse(o.get("flags").toString().contains("PROVISIONAL_SCALE"));
                measured++;
            }
            assertTrue(measured >= 8);
        }
    }

    @Test
    void aSetOfAnotherParameterSetRelaysAsNotCalibratedWithNoEvidence() throws Exception {
        JsonNode other = null;
        for (JsonNode r : records("structure-tools-records.json")) {
            if (r.get("name").asText().contains("another parameter set")) {
                other = r;
            }
        }
        assertNotNull(other);
        try (GatewayAvroDeserializer d = deserializer("bc-v1", "t.bcv", TOOLS_SUBJECT, "StructureToolsSet", 111)) {
            var relay = TimeframeSetRelay.structureTools();
            JsonNode frame = frameData(relay.onLive(TimeframeSetRelay.TOOLS_EVENT, d.deserialize("t.bcv", Base64.getDecoder().decode(other.get("framedBase64").asText()))));
            for (JsonNode o : frame.get("objects")) {
                assertEquals("UNVALIDATED", o.get("calibration").asText());
                assertEquals("NOT_CALIBRATED", o.get("calibrationState").asText());
                assertTrue(o.get("measuredEdge").isNull());
                assertTrue(o.get("evidence").isNull());
            }
        }
    }

    @Test
    void everyRealGeometryRecordIsRelayedAsTheExactJsonTheProducerSideDecodingWrote() throws Exception {
        JsonNode records = records("geometry-records.json");
        assertEquals(4, records.size());
        try (GatewayAvroDeserializer d = deserializer("bc-geometry", "t.bcg", GEOMETRY_SUBJECT, "GeometryAnnotationSet", 121)) {
            for (JsonNode r : records) {
                byte[] bytes = Base64.getDecoder().decode(r.get("framedBase64").asText());
                assertEquals(121, java.nio.ByteBuffer.wrap(bytes, 1, 4).getInt(), "the producer's own frame");
                Object decoded = d.deserialize("t.bcg", bytes);
                assertTrue(decoded instanceof GenericRecord, r.get("name").asText() + " must decode, not be UNDECODABLE");
                var relay = TimeframeSetRelay.geometry();
                String[] frame = relay.onLive(r.get("event").asText(), decoded);
                assertEquals(TimeframeSetRelay.GEOMETRY_EVENT, frame[0]);
                JsonNode json = frameData(frame);
                assertEquals(r.get("data"), json, r.get("name").asText() + ": the frame is the record, verbatim");
                for (JsonNode a : json.get("annotations")) {
                    JsonNode c = a.get("calibration");
                    assertEquals("UNKNOWN", c.get("state").asText(), "the producer writes UNKNOWN on every record");
                    assertEquals("CALIBRATED", c.get("calibrationState").asText());
                    assertEquals("CPC-CAL-1#f1cf2845", c.get("evidence").get("validationResultId").asText());
                    assertTrue(c.get("evidence").get("statement").asText().contains("history 2021-01-04..2026-10-09"));
                    assertFalse(a.get("scaleStatus").asText().equals("PROVISIONAL_SCALE"));
                }
                assertEquals(0, relay.dropsForTest());
            }
        }
    }

    @Test
    void theRealCalibratedSetsFitTheHelloPartsAndTheFrameBound() throws Exception {
        try (GatewayAvroDeserializer d = deserializer("bc-size", "t.bcz", TOOLS_SUBJECT, "StructureToolsSet", 111)) {
            long largest = 0;
            for (JsonNode r : records("structure-tools-records.json")) {
                var relay = TimeframeSetRelay.structureTools();
                String[] frame = relay.onLive(TimeframeSetRelay.TOOLS_EVENT, d.deserialize("t.bcz", Base64.getDecoder().decode(r.get("framedBase64").asText())));
                int size = StudiesRelay.utf8Length(frame[1]);
                assertTrue(size < TaRelay.FRAME_MAX_BYTES, r.get("name").asText());
                largest = Math.max(largest, size);
                assertTrue(StudiesRelay.utf8Length(relay.helloField(Long.MAX_VALUE)) < TimeframeSetRelay.HELLO_PART_BYTES);
            }
            // the largest real set (71 objects, 5m) fits the 384 KiB tools part with room for a second set of its size: the hello keeps the sets that fit, whole, and sends null for the rest
            assertTrue(largest * 2 < TimeframeSetRelay.HELLO_PART_BYTES, "largest real tools frame: " + largest);
        }
        try (GatewayAvroDeserializer d = deserializer("bc-size", "t.bcy", GEOMETRY_SUBJECT, "GeometryAnnotationSet", 121)) {
            for (JsonNode r : records("geometry-records.json")) {
                var relay = TimeframeSetRelay.geometry();
                String[] frame = relay.onLive(TimeframeSetRelay.GEOMETRY_EVENT, d.deserialize("t.bcy", Base64.getDecoder().decode(r.get("framedBase64").asText())));
                assertTrue(StudiesRelay.utf8Length(frame[1]) * 3 < TimeframeSetRelay.HELLO_PART_BYTES, r.get("name").asText());
            }
        }
    }

    @Test
    void aVersion1RecordOfAnUpgradedRegistryStillRelaysAndCarriesNoInventedFields() throws Exception {
        // the version-1 schemas under the ids a not-yet-upgraded producer stamps (2211, 2221): the relay renders the WRITER schema, so the frame has no evidence
        String scope = "bc-v1";
        SchemaRegistryClient registry = io.confluent.kafka.schemaregistry.testutil.MockSchemaRegistry.getClientForScope(scope);
        registry.register(TOOLS_SUBJECT, new AvroSchema(schema("ta-v1", "StructureToolsSet")), 1, 2211);
        registry.register(GEOMETRY_SUBJECT, new AvroSchema(schema("ta-v1", "GeometryAnnotationSet")), 1, 2221);
        registry.register(TOOLS_SUBJECT, new AvroSchema(schema("ta", "StructureToolsSet")), 2, 2212);
        registry.register(GEOMETRY_SUBJECT, new AvroSchema(schema("ta", "GeometryAnnotationSet")), 2, 2223);
        Map<String, Object> config = new HashMap<>();
        config.put("schema.registry.url", "mock://" + scope);
        config.put("auto.register.schemas", false);
        config.put("use.latest.version", false);
        config.put("value.subject.name.strategy", "io.confluent.kafka.serializers.subject.RecordNameStrategy");
        Map<String, Object> reader = new HashMap<>(config);
        reader.put("specific.avro.reader", "false");
        reader.put(GatewayAvroDeserializer.SPX_PRICE_TOPIC, "underlying.spx.price");
        reader.put(GatewayAvroDeserializer.TOLERANT_TOPICS, "t.bc1");
        GenericRecord oldTools = TaFixtures.minimal(schema("ta-v1", "StructureToolsSet"));
        TaFixtures.put(oldTools, "schemaVersion", 1);
        TaFixtures.put(oldTools, "service", "market-structure");
        TaFixtures.put(oldTools, "state", "OK");
        TaFixtures.put(oldTools, "timeframe", "M5");
        TaFixtures.put(oldTools, "asOfMs", 1_790_000_000_001L);
        try (KafkaAvroSerializer serializer = new KafkaAvroSerializer(); GatewayAvroDeserializer d = new GatewayAvroDeserializer()) {
            serializer.configure(config, false);
            d.configure(reader, false);
            var relay = TimeframeSetRelay.structureTools();
            byte[] bytes = serializer.serialize("t.bc1", oldTools);
            assertEquals(2211, java.nio.ByteBuffer.wrap(bytes, 1, 4).getInt(), "the serializer finds the exact schema, so a version-1 record keeps its version-1 id");
            JsonNode t = frameData(relay.onLive(TimeframeSetRelay.TOOLS_EVENT, d.deserialize("t.bc1", bytes)));
            assertEquals(1, relay.acceptedForTest());
            assertFalse(t.has("evidence"));
        }
    }
}
