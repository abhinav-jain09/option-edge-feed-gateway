/**
 * The INDICATOR-STUDIES calibrated release (StudyBar version 2, id 2505; StudiesCurrent version 2, id 2506): the studies relay forwards the measured evidence VERBATIM. The records here
 * are the bytes the REAL producer serializer wrote (indicator-service of options-edge-processing 89664fa1d: the producer's records with the real StudyCalibration of the running
 * parameter set, the 102-row SPX and the 35-row ES summary, framed by StudyAvro; generated by the web repository's scripts/studies-fixtures/StudiesFixtureGen): they pass through the
 * production {@link GatewayAvroDeserializer} against a registry holding the version-2 schemas under the producer's ids, then through {@link StudiesRelay}; each frame must equal, node for
 * node, the JSON the generator wrote from the record by its OWN code (independent of the gateway's renderer).
 */
class StudiesProducerRecordsTest {
    private static final ObjectMapper JSON = new ObjectMapper();
    private static final String BAR_SUBJECT = "com.optionsedge.contracts.indicators.avro.StudyBar", CURRENT_SUBJECT = "com.optionsedge.contracts.indicators.avro.StudiesCurrent";
    private static final List<String> SCOPES = List.of("studies-real", "studies-v1");

    @AfterAll
    static void dropScopes() {
        SCOPES.forEach(io.confluent.kafka.schemaregistry.testutil.MockSchemaRegistry::dropScope);
    }

    private static JsonNode records() throws Exception {
        try (InputStream in = StudiesProducerRecordsTest.class.getResourceAsStream("/ta-producer/studies-records.json")) {
            return JSON.readTree(in).get("records");
        }
    }

    private static Schema schema(String dir, String name) throws Exception {
        try (InputStream in = StudiesProducerRecordsTest.class.getResourceAsStream("/" + dir + "/" + name + ".avsc")) {
            return new Schema.Parser().parse(new String(in.readAllBytes(), java.nio.charset.StandardCharsets.UTF_8));
        }
    }

    private static Map<String, Object> readerConfig(String scope, String topic) {
        Map<String, Object> reader = new HashMap<>();
        reader.put("schema.registry.url", "mock://" + scope);
        reader.put("auto.register.schemas", false);
        reader.put("value.subject.name.strategy", "io.confluent.kafka.serializers.subject.RecordNameStrategy");
        reader.put("specific.avro.reader", "false");
        reader.put(GatewayAvroDeserializer.SPX_PRICE_TOPIC, "underlying.spx.price");
        reader.put(GatewayAvroDeserializer.TOLERANT_TOPICS, topic);
        return reader;
    }

    private static GatewayAvroDeserializer deserializer(String scope, String topic) throws Exception {
        SchemaRegistryClient registry = io.confluent.kafka.schemaregistry.testutil.MockSchemaRegistry.getClientForScope(scope);
        registry.register(BAR_SUBJECT, new AvroSchema(schema("studies", "StudyBar")), 1, 2505);
        registry.register(CURRENT_SUBJECT, new AvroSchema(schema("studies", "StudiesCurrent")), 1, 2506);
        GatewayAvroDeserializer d = new GatewayAvroDeserializer();
        d.configure(readerConfig(scope, topic), false);
        return d;
    }

    @Test
    void everyRealProducerRecordIsRelayedAsTheExactJsonTheProducerSideDecodingWrote() throws Exception {
        JsonNode records = records();
        assertEquals(8, records.size(), "bars of 1m, 5m, 15m and the current state, for SPX and ES");
        try (GatewayAvroDeserializer d = deserializer("studies-real", "t.sr")) {
            var relay = new StudiesRelay(JSON);
            for (JsonNode r : records) {
                byte[] bytes = Base64.getDecoder().decode(r.get("framedBase64").asText());
                int id = java.nio.ByteBuffer.wrap(bytes, 1, 4).getInt();
                assertEquals(r.get("event").asText().equals("indicator-studies") ? 2505 : 2506, id, "the producer's own fixed id");
                Object decoded = d.deserialize("t.sr", bytes);
                assertTrue(decoded instanceof GenericRecord, r.get("name").asText() + " must decode, not be UNDECODABLE");
                String frame = relay.onLive(r.get("event").asText(), r.get("key").asText(), decoded, "ES".equals(r.get("symbol").asText()));
                assertNotNull(frame, r.get("name").asText());
                JsonNode got = JSON.readTree(frame);
                JsonNode want = r.get("data");
                if (r.get("event").asText().equals("indicator-studies-current")) {
                    // the relay forwards three of the six timeframes; every other field, the calibration summary included, is the record's
                    assertEquals(List.of("1m", "5m", "15m"), fieldNames(got.get("timeframes")));
                    for (String f : fieldNames(want)) {
                        if (!f.equals("timeframes")) {
                            assertEquals(want.get(f), got.get(f), r.get("name").asText() + " " + f);
                        }
                    }
                    for (String tf : List.of("1m", "5m", "15m")) {
                        assertEquals(want.get("timeframes").get(tf), got.get("timeframes").get(tf), tf);
                    }
                } else {
                    assertEquals(want, got, r.get("name").asText() + ": the frame is the record, verbatim");
                    assertEquals(want.get("validationResultId"), got.get("validationResultId"));
                    assertTrue(got.get("validationResultId").asText().startsWith("ISC-CAL-1#"));
                }
            }
            assertEquals(0, relay.dropsForTest());
            assertEquals(0, relay.regressionsForTest());
        }
    }

    private static List<String> fieldNames(JsonNode n) {
        List<String> out = new java.util.ArrayList<>();
        n.fieldNames().forEachRemaining(out::add);
        return out;
    }

    @Test
    void theMeasuredSummaryReachesTheHelloAndTheLiveFrameWithItsFixedStatementsUntouched() throws Exception {
        try (GatewayAvroDeserializer d = deserializer("studies-real", "t.sh")) {
            var relay = new StudiesRelay(JSON);
            for (JsonNode r : records()) {
                relay.onLive(r.get("event").asText(), r.get("key").asText(), d.deserialize("t.sh", Base64.getDecoder().decode(r.get("framedBase64").asText())), "ES".equals(r.get("symbol").asText()));
            }
            JsonNode hello = JSON.readTree("{\"hello\":1" + relay.helloFields() + "}");
            for (String[] f : new String[][] {{"studies", "SPX", "102"}, {"esStudies", "ES", "35"}}) {
                for (String tf : List.of("1m", "5m", "15m")) {
                    JsonNode cur = hello.get(f[0]).get(tf);
                    assertFalse(cur.isNull(), f[0] + " " + tf + " must fit the hello");
                    assertEquals("CALIBRATED", cur.get("calibration").asText());
                    JsonNode cs = cur.get("calibrationSummary");
                    assertEquals("CALIBRATED", cs.get("state").asText());
                    assertEquals(Integer.parseInt(f[2]), cs.get("results").size(), f[1] + " rows");
                    assertEquals("f40c7965c935e19f1085d5849dd94bac0ea3f2867da08d96edbb337eb8284f3e", cs.get("datasetSha256").asText());
                    for (JsonNode row : cs.get("results")) {
                        assertTrue(row.get("statement").asText().length() > 0);
                        assertTrue(List.of("NONE", "POSITIVE", "NOT_TESTABLE", "EXACT_CONSTRUCT").contains(row.get("measuredEdge").asText()));
                    }
                }
            }
            assertTrue(StudiesRelay.utf8Length(relay.helloFields()) <= StudiesRelay.HELLO_MAX_BYTES);
        }
    }

    @Test
    void theHelloBudgetWithTheRealSummariesIsRecomputedNotAssumed() throws Exception {
        // the summary rides in the header of every per-timeframe entry of the hello: 3 x SPX (about 29.5 KB) + 3 x ES (about 10 KB) over the pre-calibration entries
        try (GatewayAvroDeserializer d = deserializer("studies-real", "t.sb")) {
            var relay = new StudiesRelay(JSON);
            int summaries = 0;
            for (JsonNode r : records()) {
                String frame = relay.onLive(r.get("event").asText(), r.get("key").asText(), d.deserialize("t.sb", Base64.getDecoder().decode(r.get("framedBase64").asText())), "ES".equals(r.get("symbol").asText()));
                if (r.get("event").asText().equals("indicator-studies-current")) {
                    int size = StudiesRelay.utf8Length(frame);
                    assertTrue(size < StudiesRelay.CURRENT_MAX_BYTES, r.get("name").asText() + " " + size);
                    summaries += StudiesRelay.utf8Length(JSON.writeValueAsString(JSON.readTree(frame).get("calibrationSummary")));
                }
            }
            int hello = StudiesRelay.utf8Length(relay.helloFields());
            assertTrue(hello < StudiesRelay.HELLO_MAX_BYTES, "hello " + hello);
            assertTrue(summaries > 15_000 && summaries < 60_000, "the live summaries of the two symbols: " + summaries);
        }
    }

    @Test
    void aVersion1RecordOfAnUpgradedRegistryStillRelaysAndCarriesNoInventedFields() throws Exception {
        // the REAL version-2 records of the producer rewritten as version 1 (DownVersion): what a producer that has not been upgraded writes, under the ids 2501 and 2502
        String scope = "studies-v1";
        SchemaRegistryClient registry = io.confluent.kafka.schemaregistry.testutil.MockSchemaRegistry.getClientForScope(scope);
        registry.register(BAR_SUBJECT, new AvroSchema(schema("studies-v1", "StudyBar")), 1, 2501);
        registry.register(CURRENT_SUBJECT, new AvroSchema(schema("studies-v1", "StudiesCurrent")), 1, 2502);
        registry.register(BAR_SUBJECT, new AvroSchema(schema("studies", "StudyBar")), 2, 2505);
        registry.register(CURRENT_SUBJECT, new AvroSchema(schema("studies", "StudiesCurrent")), 2, 2506);
        Map<String, Object> config = new HashMap<>();
        config.put("schema.registry.url", "mock://" + scope);
        config.put("auto.register.schemas", false);
        config.put("use.latest.version", false);
        config.put("value.subject.name.strategy", "io.confluent.kafka.serializers.subject.RecordNameStrategy");
        try (GatewayAvroDeserializer real = deserializer("studies-real", "t.s2"); KafkaAvroSerializer serializer = new KafkaAvroSerializer(); GatewayAvroDeserializer d = new GatewayAvroDeserializer()) {
            serializer.configure(config, false);
            d.configure(readerConfig(scope, "t.s1"), false);
            var relay = new StudiesRelay(JSON);
            for (JsonNode r : records()) {
                if (!r.get("symbol").asText().equals("SPX") || !r.get("timeframe").asText().equals(r.get("event").asText().equals("indicator-studies") ? "5m" : "ALL")) {
                    continue;
                }
                boolean bar = r.get("event").asText().equals("indicator-studies");
                GenericRecord v2 = (GenericRecord) real.deserialize("t.s2", Base64.getDecoder().decode(r.get("framedBase64").asText()));
                GenericRecord v1 = DownVersion.to(v2, bar ? StudiesFixtures.BAR_V1 : StudiesFixtures.CURRENT_V1);
                byte[] bytes = serializer.serialize("t.s1", v1);
                assertEquals(bar ? 2501 : 2502, java.nio.ByteBuffer.wrap(bytes, 1, 4).getInt(), "a version-1 record keeps its version-1 id");
                String frame = relay.onLive(r.get("event").asText(), r.get("key").asText(), d.deserialize("t.s1", bytes), false);
                assertNotNull(frame, "the approved version-1 writer schema still relays: " + r.get("name").asText());
                JsonNode n = JSON.readTree(frame);
                assertFalse(n.has("validationResultId") || n.has("calibrationSummary"), "a version-1 frame carries no evidence field");
                if (bar) {
                    assertEquals(v2.get("barId").toString(), n.get("barId").asText());
                } else {
                    assertEquals(List.of("1m", "5m", "15m"), fieldNames(n.get("timeframes")), "the projected current state of version 1");
                }
            }
            assertEquals(0, relay.dropsForTest());
            assertEquals(2, relay.acceptedForTest());
        }
    }
}
