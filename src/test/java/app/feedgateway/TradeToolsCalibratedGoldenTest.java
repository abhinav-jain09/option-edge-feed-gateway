package app.feedgateway;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;
import java.util.Set;
import org.apache.avro.Schema;
import org.apache.avro.generic.GenericDatumReader;
import org.apache.avro.generic.GenericRecord;
import org.apache.avro.io.DecoderFactory;
import org.junit.jupiter.api.Test;

/**
 * TICK-TRADE-TOOLS revision 21 with REAL producer output: src/test/resources/tt-golden holds Avro datums written by es-trade-tools-service's own
 * TradeToolsEngine (Wire.encode: the topic value minus the Confluent frame; generated by options-edge scripts/trade-tools-fixtures/TradeToolsFixtureGen.java
 * at processing 7b6294e0 / main 48ba5e86) together with the plain JSON the frame contract requires. Every record carries CALIBRATED / MEASURED and the
 * evidence block. The relay must accept each, and its frame must be that JSON field for field (evidence verbatim, nulls present, a union as its bare value).
 */
class TradeToolsCalibratedGoldenTest {
    private static final Path DIR = Path.of("src", "test", "resources", "tt-golden");
    private static final ObjectMapper JSON = new ObjectMapper();
    private static final String[] ROLE_OF_FRAME_PREFIX = {"trade-tools-pf-chart", "trade-tools-pf-column", "trade-tools-pf-events", "trade-tools-volume-nodes",
        "trade-tools-flow-bar", "trade-tools-climax"};

    private record Entry(String name, String record, String frame, String edge, String sha256, String jsonSha256) {
    }

    private static List<Entry> manifest() throws Exception {
        List<Entry> out = new ArrayList<>();
        for (String line : Files.readAllLines(DIR.resolve("MANIFEST.tsv"))) {
            if (!line.isBlank()) {
                String[] f = line.split("\t");
                out.add(new Entry(f[0], f[1], f[2], f[3], f[4], f[5]));
            }
        }
        return out;
    }

    private static String role(String frame) {
        return switch (frame) {
            case "trade-tools-pf-chart" -> ROLE_OF_FRAME_PREFIX[0];
            case "trade-tools-pf-column" -> ROLE_OF_FRAME_PREFIX[1];
            case "trade-tools-volume-nodes" -> ROLE_OF_FRAME_PREFIX[3];
            case "trade-tools-flow-bar" -> ROLE_OF_FRAME_PREFIX[4];
            case "trade-tools-climax" -> ROLE_OF_FRAME_PREFIX[5];
            default -> ROLE_OF_FRAME_PREFIX[2];   // the seven P&F event kinds share one topic
        };
    }

    private static GenericRecord decode(Entry e) throws Exception {
        byte[] bytes = Files.readAllBytes(DIR.resolve(e.name() + ".avro"));
        assertEquals(e.sha256(), HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes)), e.name() + " datum drifted from the manifest");
        Schema writer = TaFixtures.schema(e.record());
        return new GenericDatumReader<GenericRecord>(writer).read(null, DecoderFactory.get().binaryDecoder(bytes, null));
    }

    @Test
    void everyProducerRecordIsRelayedAsTheContractsJsonWithTheEvidenceVerbatim() throws Exception {
        var relay = new TradeToolsRelay();
        List<Entry> entries = manifest();
        assertTrue(entries.size() >= 20, "the set covers every record type and every evidence row kind");
        Set<String> records = new java.util.TreeSet<>();
        Set<String> edges = new java.util.TreeSet<>();
        for (Entry e : entries) {
            GenericRecord r = decode(e);
            assertEquals("CALIBRATED", r.get("calibration").toString(), e.name());
            assertEquals("MEASURED", r.get("validation").toString(), e.name());
            assertNotNull(r.get("evidence"), e.name());
            String[] frame = relay.onLive(role(e.frame()), r);
            assertNotNull(frame, e.name() + " (" + e.record() + ") must be relayed: a MEASURED record is not malformed");
            assertEquals(e.frame(), frame[0], e.name());
            byte[] expectedBytes = Files.readAllBytes(DIR.resolve(e.name() + ".json"));
            assertEquals(e.jsonSha256(), HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(expectedBytes)), e.name() + ": the expected JSON drifted from the manifest");
            JsonNode expected = JSON.readTree(expectedBytes);
            JsonNode got = JSON.readTree(frame[1]);
            assertEquals(expected, got, e.name() + ": the frame is the contract's JSON, every field, evidence unaltered");
            JsonNode ev = got.get("evidence");
            assertEquals(17, ev.size(), "the Evidence record has exactly its seventeen fields, nulls present");
            assertEquals(e.edge(), ev.get("measuredEdge").asText(), e.name());
            assertTrue(ev.get("statement").asText().length() <= 300 && ev.get("claim").asText().length() <= 100, e.name());
            records.add(e.record());
            edges.add(e.edge());
        }
        assertEquals(12, records.size(), "all twelve display records");
        assertEquals(Set.of("EXACT_CONSTRUCT", "NONE", "NOT_TESTABLE"), edges, "every measured-edge kind the producer writes today");
        assertEquals(0, relay.dropsForTest());
        assertEquals(entries.size(), relay.acceptedForTest());
    }

    @Test
    void theOneMinuteFlowBarCarriesTheReconciliationCounts() throws Exception {
        boolean seen = false;
        for (Entry e : manifest()) {
            if (e.record().equals("FlowBar")) {
                JsonNode ev = JSON.readTree(Files.readString(DIR.resolve(e.name() + ".json"))).get("evidence");
                if (ev.get("reconComparedBars").isNumber()) {
                    seen = true;
                    assertEquals("EXACT_CONSTRUCT", ev.get("measuredEdge").asText());
                    assertEquals(56482, ev.get("reconComparedBars").asLong());
                    assertEquals(50029, ev.get("reconEqualBars").asLong());
                    assertEquals(1, ev.get("reconUnexplainedBars").asLong());
                }
            }
        }
        assertTrue(seen, "an M1 FlowBar with the D-V15 counts is among the golden records");
    }

    @Test
    void theHelloBundleCarriesTheEvidenceUnaltered() throws Exception {
        var relay = new TradeToolsRelay();
        for (Entry e : manifest()) {
            relay.onLive(role(e.frame()), decode(e));
        }
        JsonNode hello = JSON.readTree("{" + relay.helloField(Long.MAX_VALUE).substring(1) + "}").get("tradeTools");
        int evidences = 0;
        for (String tf : List.of("1m", "5m", "15m")) {
            JsonNode bundle = hello.get(tf);
            if (bundle.isNull()) {
                continue;
            }
            for (JsonNode array : bundle) {
                for (JsonNode record : array) {
                    assertEquals("MEASURED", record.get("validation").asText());
                    assertEquals(17, record.get("evidence").size());
                    evidences++;
                }
            }
        }
        assertTrue(evidences > 10, "the retained golden records ride the hello with their evidence (" + evidences + ")");
    }
}
